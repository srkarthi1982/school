#!/usr/bin/env node
import { writeFileSync } from 'fs'
import { resolve, dirname } from 'path'
import { fileURLToPath } from 'url'
import { loadEnv } from 'vite'

const __dirname = dirname(fileURLToPath(import.meta.url))
const env = loadEnv('development', resolve(__dirname, '..'), '')
const BACKEND_URL = env.VITE_BACKEND_URL || 'http://localhost:8000'
const ENDPOINT = `${BACKEND_URL}/api/v1/access/permission-codes`
const OUTPUT = resolve(__dirname, '../src/infra/shared/types/permissions.gen.ts')

const res = await fetch(ENDPOINT)
if (!res.ok) {
  console.error(`❌ Failed to fetch ${ENDPOINT}: ${res.status} ${res.statusText}`)
  console.error(`   Is the backend running on ${BACKEND_URL}?`)
  process.exit(1)
}

const json = await res.json()
const codes = json?.data
if (!Array.isArray(codes) || codes.length === 0) {
  console.error('❌ Unexpected response shape:', json)
  process.exit(1)
}

const literals = codes.map(c => `  | '${c}'`).join('\n')
const arrayLits = codes.map(c => `  '${c}',`).join('\n')

const out = `// AUTO-GENERATED by scripts/gen-permissions.mjs — do not edit manually.
// Run \`npm run generate-permissions\` after backend permission changes.

export type PermissionCode =
${literals}

export const ALL_PERMISSION_CODES: PermissionCode[] = [
${arrayLits}
]
`
writeFileSync(OUTPUT, out)
console.log(`✅ Generated ${codes.length} permission codes → ${OUTPUT}`)
